// Emits OpcodesUnverified.h: every SMSG whose Opcodes.h value still carries a TODO(verify) marker.
// WorldSession::SendPacket drops these (logged by name) so a wrong mapping cannot crash the client.
// Usage: bun src/gen_unverified.ts <repo root>

const hex6 = (v: number) => "0x" + v.toString(16).toUpperCase().padStart(6, "0");

export function unverifiedServerOpcodes(opcodesH: string): { name: string; value: number }[] {
  const out: { name: string; value: number }[] = [];
  for (const m of opcodesH.matchAll(/^    (SMSG_\w+)\s*= (0x[0-9A-F]+),\s*\/\/ TODO\(verify\)/gm))
    out.push({ name: m[1], value: parseInt(m[2], 16) });
  return out.sort((a, b) => a.value - b.value);
}

