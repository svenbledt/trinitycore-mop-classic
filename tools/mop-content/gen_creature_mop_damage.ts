// Generates the world update that corrects creature_classlevelstats_mop.basedamage.
// SkyFire damage_exp4 is on another scale (level 5 warrior: 13.0 vs client NpcDamageByClassExp3 3.18); retail 70449 Tushui
// Monk (59649, level 5, 2.0 s) hits 12-16, i.e. base ~3.7 with our formula. Levels <= 85 use the client table; 86+ continue
// SkyFire's exp4 curve rescaled so level 85 equals the client value. TODO(verify) 86-90 against retail sniffs.
// usage: bun tools/mop-content/gen_creature_mop_damage.ts <gt dir> [out] [container]
import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";

const gtDir = process.argv[2] ?? "F:/WorkDir/mop-clientdata/70449/gt";
const out = process.argv[3] ?? "sql/updates/world/mop_classic/2026_10_19_28_world.sql";
const container = process.argv[4] ?? "tc-mop-db-1";

function query(sql: string): string[][] {
  const res = execFileSync("docker", ["exec", container, "mysql", "-uroot", "-proot", "-N", "-B", "-e", sql], { encoding: "utf8", stdio: ["ignore", "pipe", "ignore"] });
  return res.split("\n").filter((l) => l.length).map((l) => l.split("\t"));
}

// unit_class mask -> GameTable column name
const columns: Record<number, string> = { 1: "Warrior", 2: "Paladin", 4: "Rogue", 8: "Mage" };
const [header, ...body] = readFileSync(`${gtDir}/NpcDamageByClassExp3.txt`, "utf8").trim().split(/\r?\n/).map((l) => l.split("\t"));
const client = new Map<string, number>();
for (const row of body)
  for (const [cls, name] of Object.entries(columns))
    client.set(`${row[0]}:${cls}`, Number(row[header.indexOf(name)]));

const skyfire = new Map<string, number>();
for (const [lv, cls, dmg] of query("SELECT level, class, damage_exp4 FROM ref_sfdb.creature_classlevelstats"))
  skyfire.set(`${lv}:${cls}`, Number(dmg));

const lines = [
  "-- MoP Classic: creature_classlevelstats_mop.basedamage from the client NpcDamageByClassExp3 table (levels <= 85),",
  "-- above 85 SkyFire's damage_exp4 curve rescaled to the client value at 85. Generated by tools/mop-content/gen_creature_mop_damage.ts.",
  "",
];
for (const [lv, cls] of query("SELECT level, class FROM world.creature_classlevelstats_mop ORDER BY level, class")) {
  const level = Number(lv);
  let dmg = client.get(`${lv}:${cls}`);
  if (level > 85 || dmg === undefined) {
    const scale = (client.get(`85:${cls}`) ?? 0) / (skyfire.get(`85:${cls}`) || 1);
    dmg = (skyfire.get(`${lv}:${cls}`) ?? 0) * scale;
  }
  lines.push(`UPDATE \`creature_classlevelstats_mop\` SET \`basedamage\` = ${Number(dmg.toPrecision(7))} WHERE \`level\` = ${lv} AND \`class\` = ${cls};`);
}
lines.push("");
writeFileSync(out, lines.join("\n"));
console.log(out, lines.length - 4, "rows");
