// Generates the world update with MoP (expansion 4) creature base stats and switches MoP creatures to them.
// The 5.5.4 client ships NpcTotalHp/NpcDamageByClass only up to Exp3; retail uses the MoP curve
// (SkyFire basehp4 x Health_mod matches 5956 of 6135 creature samples in the 70449 island sniffs).
// usage: bun tools/mop-content/gen_creature_mop_stats.ts [out] [container]
import { execFileSync } from "node:child_process";
import { writeFileSync } from "node:fs";

const out = process.argv[2] ?? "sql/updates/world/mop_classic/2026_10_19_01_world.sql";
const container = process.argv[3] ?? "tc-mop-db-1";

function query(sql: string): string[][] {
  const res = execFileSync("docker", ["exec", container, "mysql", "-uroot", "-proot", "-N", "-B", "-e", sql], { encoding: "utf8", stdio: ["ignore", "pipe", "ignore"] });
  return res.split("\n").filter((l) => l.length).map((l) => l.split("\t"));
}

const stats = query("SELECT level, class, basehp4, damage_exp4 FROM ref_sfdb.creature_classlevelstats ORDER BY level, class");
// Only creatures SkyFire marks as MoP and that exist in our world DB
const creatures = query(
  "SELECT s.entry, s.Health_mod FROM ref_sfdb.creature_template s " +
  "JOIN world.creature_template_difficulty w ON w.Entry = s.entry AND w.DifficultyID = 0 " +
  "WHERE s.exp = 4 ORDER BY s.entry");

const lines: string[] = [];
lines.push("-- MoP Classic: creature base stats for expansion 4 (MoP), missing from the 5.5.4 client game tables.");
lines.push("-- Generated by tools/mop-content/gen_creature_mop_stats.ts; do not edit by hand.");
lines.push("-- Source: SkyFire 5.4.8 creature_classlevelstats basehp4/damage_exp4 and creature_template exp/Health_mod (ref_sfdb).");
lines.push("-- Checked against retail 5.5.4.70449 Wandering Isle sniffs: 97% of creature MaxHealth values match exactly.");
lines.push("");
lines.push("CREATE TABLE IF NOT EXISTS `creature_classlevelstats_mop` (");
lines.push("  `level` tinyint NOT NULL,");
lines.push("  `class` tinyint NOT NULL,");
lines.push("  `basehp` int unsigned NOT NULL DEFAULT '1',");
lines.push("  `basedamage` float NOT NULL DEFAULT '0',");
lines.push("  PRIMARY KEY (`level`,`class`)");
lines.push(") ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT='MoP (expansion 4) creature base health and damage';");
lines.push("");
lines.push("DELETE FROM `creature_classlevelstats_mop`;");
lines.push("INSERT INTO `creature_classlevelstats_mop` (`level`, `class`, `basehp`, `basedamage`) VALUES");
lines.push(stats.map(([lv, cl, hp, dmg]) => `(${lv}, ${cl}, ${hp}, ${Number(dmg)})`).join(",\n") + ";");
lines.push("");
lines.push(`-- ${creatures.length} creatures SkyFire marks as MoP: use the MoP curve and SkyFire's health modifier`);
for (const [entry, mod] of creatures)
  lines.push(`UPDATE \`creature_template_difficulty\` SET \`HealthScalingExpansion\` = 4, \`HealthModifier\` = ${Number(mod)} WHERE \`Entry\` = ${entry} AND \`DifficultyID\` = 0;`);
lines.push("");

writeFileSync(out, lines.join("\n"));
console.log(out, stats.length, "stat rows,", creatures.length, "creatures");
