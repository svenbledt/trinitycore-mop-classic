// Generates creature quest-item drops for Pandaria (map 870): every item TC master lists in creature_questitem drops at 100%
// while the player has the quest (QuestRequired = 1). Neither SkyFire nor master has real rates for these (user decision 2026-10-19).
// usage: bun tools/mop-content/gen_pandaria_questitems.ts <db2 dir> [out] [container]
import { execFileSync } from "node:child_process";
import { writeFileSync } from "node:fs";
import { readDb2 } from "./src/db2.ts";

const db2Dir = process.argv[2] ?? "F:/WorkDir/mop-clientdata/70449/dbc/enUS";
const out = process.argv[3] ?? "sql/updates/world/mop_classic/2026_10_19_27_world.sql";
const container = process.argv[4] ?? "tc-mop-db-1";
const defs = new URL("../mop-re/refs/wowdbdefs/definitions/", import.meta.url).pathname.replace(/^\/([A-Za-z]:)/, "$1");

function query(sql: string): string[][] {
  const res = execFileSync("docker", ["exec", container, "mysql", "-uroot", "-proot", "-N", "-B", "-e", sql], { encoding: "utf8", stdio: ["ignore", "pipe", "ignore"], maxBuffer: 1 << 28 });
  return res.split("\n").filter((l) => l.length).map((l) => l.split("\t"));
}

const clientItems = new Set(readDb2(`${db2Dir}/Item.db2`, `${defs}Item.dbd`).rows.map((r) => r.ID as number));

const rows = query(
  "SELECT DISTINCT q.CreatureEntry, q.ItemId, d.LootID FROM ref_master.creature_questitem q " +
  "JOIN world.creature_template_difficulty d ON d.Entry = q.CreatureEntry AND d.DifficultyID = 0 " +
  "WHERE q.DifficultyID = 0 AND EXISTS (SELECT 1 FROM world.creature c WHERE c.id = q.CreatureEntry AND c.map = 870) " +
  "ORDER BY q.CreatureEntry, q.ItemId");
const existing = new Set(query("SELECT Entry, Item FROM world.creature_loot_template").map(([e, i]) => `${e}:${i}`));

const lines = [
  "-- MoP Classic: Pandaria creature quest-item drops from TC master creature_questitem, 100% while on the quest.",
  "-- TODO(verify): drop rates are placeholders until retail sniffs give real ones. Generated by tools/mop-content/gen_pandaria_questitems.ts.",
  "",
];
const lootIds = new Map<number, number>();
const inserts: string[] = [];
let skipped = 0;
for (const [entryS, itemS, lootS] of rows) {
  const entry = Number(entryS), item = Number(itemS);
  if (!clientItems.has(item)) { ++skipped; continue; }
  const lootId = Number(lootS) || entry;
  lootIds.set(entry, lootId);
  if (existing.has(`${lootId}:${item}`)) continue;
  inserts.push(`(${lootId}, 0, ${item}, 100, 1, 1, 0, 1, 1, 'quest item (master creature_questitem)')`);
}
for (const [entry, lootId] of lootIds)
  lines.push(`UPDATE \`creature_template_difficulty\` SET \`LootID\` = ${lootId} WHERE \`Entry\` = ${entry} AND \`DifficultyID\` = 0 AND \`LootID\` = 0;`);
if (inserts.length) {
  lines.push("INSERT IGNORE INTO `creature_loot_template` (`Entry`, `ItemType`, `Item`, `Chance`, `QuestRequired`, `LootMode`, `GroupId`, `MinCount`, `MaxCount`, `Comment`) VALUES");
  lines.push(inserts.join(",\n") + ";");
}
lines.push("");
writeFileSync(out, lines.join("\n"));
console.log(out, lootIds.size, "creatures,", inserts.length, "drops,", skipped, "items not in the client");
