// Generates a world update putting every creature on its MoP state from SkyFire 5.4.8: level range, MoP health curve
// (expansion 4) and SkyFire's health modifier. Creatures covered by the retail-sniff update keep those values (sniff > SkyFire).
// Rule check vs retail 70449 sniffs: MoP curve x SkyFire Health_mod matches 84% of 1665 creatures (SkyFire's exp column: 50%).
// usage: bun tools/mop-content/gen_creature_skyfire_levels.ts [out] [sniff update sql] [container]
import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";

const out = process.argv[2] ?? "sql/updates/world/mop_classic/2026_10_19_04_world.sql";
const sniffSql = process.argv[3] ?? "sql/updates/world/mop_classic/2026_10_19_02_world.sql";
const container = process.argv[4] ?? "tc-mop-db-1";

function query(sql: string): string[][] {
  const res = execFileSync("docker", ["exec", container, "mysql", "-uroot", "-proot", "-N", "-B", "-e", sql], { encoding: "utf8", stdio: ["ignore", "pipe", "ignore"], maxBuffer: 1 << 28 });
  return res.split("\n").filter((l) => l.length).map((l) => l.split("\t"));
}

const sniffed = new Set<number>();
for (const m of readFileSync(sniffSql, "utf8").matchAll(/`Entry` = (\d+)/g)) sniffed.add(Number(m[1]));

const rows = query(
  "SELECT s.entry, s.minlevel, s.maxlevel, s.Health_mod FROM ref_sfdb.creature_template s " +
  "JOIN world.creature_template_difficulty w ON w.Entry = s.entry AND w.DifficultyID = 0 " +
  "WHERE s.minlevel > 0 AND s.maxlevel >= s.minlevel AND s.Health_mod > 0 ORDER BY s.entry");

const lines = [
  "-- MoP Classic: creature levels and health on their MoP state from SkyFire 5.4.8 (ref_sfdb.creature_template minlevel/maxlevel/Health_mod),",
  "-- health on the MoP curve (creature_classlevelstats_mop). Entries in 2026_10_19_02 (retail sniffs) are left as sniffed.",
  "-- Generated by tools/mop-content/gen_creature_skyfire_levels.ts; do not edit by hand.",
  "",
];
let count = 0;
for (const [entry, minLevel, maxLevel, mod] of rows) {
  if (sniffed.has(Number(entry)))
    continue;
  lines.push(`UPDATE \`creature_template_difficulty\` SET \`MinLevel\` = ${minLevel}, \`MaxLevel\` = ${maxLevel}, \`HealthScalingExpansion\` = 4, \`HealthModifier\` = ${Number(mod)} WHERE \`Entry\` = ${entry} AND \`DifficultyID\` = 0;`);
  ++count;
}
lines.push("");
writeFileSync(out, lines.join("\n"));
console.log(out, count, "creatures,", sniffed.size, "kept from sniffs");
