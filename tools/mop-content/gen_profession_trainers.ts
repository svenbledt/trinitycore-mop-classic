// Generates trainer_spell for every tradeskill trainer (trainer.Type 2) that has no spells: the profession comes from the spell
// TC master lists for that trainer (client SkillLineAbility), the MoP spell list from SkyFire 5.4.8's npc_trainer reference
// lists (200300-200410), limited to spells the 5.5.4 client has. Also links Whittler Dewei's sniffed menus to the trainers.
// usage: bun tools/mop-content/gen_profession_trainers.ts <db2 dir> [out] [container]
import { execFileSync } from "node:child_process";
import { writeFileSync } from "node:fs";
import { readDb2 } from "./src/db2.ts";

const db2Dir = process.argv[2] ?? "F:/WorkDir/mop-clientdata/70449/dbc/enUS";
const out = process.argv[3] ?? "sql/updates/world/mop_classic/2026_10_19_37_world.sql";
const container = process.argv[4] ?? "tc-mop-db-1";
const defs = new URL("../mop-re/refs/wowdbdefs/definitions/", import.meta.url).pathname.replace(/^\/([A-Za-z]:)/, "$1");

function query(sql: string): string[][] {
  const res = execFileSync("docker", ["exec", container, "mysql", "-uroot", "-proot", "-N", "-B", "-e", sql], { encoding: "utf8", stdio: ["ignore", "pipe", "ignore"], maxBuffer: 1 << 28 });
  return res.split("\n").filter((l) => l.length).map((l) => l.split("\t"));
}

const clientSpells = new Set(readDb2(`${db2Dir}/SpellName.db2`, `${defs}SpellName.dbd`).rows.map((r) => r.ID as number));
const skillOfSpell = new Map<number, number>();
for (const r of readDb2(`${db2Dir}/SkillLineAbility.db2`, `${defs}SkillLineAbility.dbd`).rows)
  if (!skillOfSpell.has(r.Spell as number)) skillOfSpell.set(r.Spell as number, r.SkillLine as number);

// SkyFire reference list per profession skill line
const LIST: Record<number, number> = {
  171: 200400, 164: 200401, 333: 200402, 202: 200403, 182: 200404, 773: 200405, 755: 200406, 165: 200407, 186: 200408,
  393: 200409, 197: 200410, 356: 200302, 129: 200303, 794: 200304, 185: 200305,
};

const sf = new Map<number, string[][]>();
for (const row of query("SELECT entry, spell, spellcost, reqskill, reqskillvalue, reqlevel FROM ref_sfdb.npc_trainer WHERE entry BETWEEN 200000 AND 202000"))
  (sf.get(Number(row[0])) ?? sf.set(Number(row[0]), []).get(Number(row[0]))!).push(row);
function resolve(list: number, seen = new Set<number>()): string[][] {
  if (seen.has(list)) return [];
  seen.add(list);
  return (sf.get(list) ?? []).flatMap((r) => (Number(r[1]) < 0 ? resolve(-Number(r[1]), seen) : [r]));
}

// tradeskill trainers without spells -> profession via master's spell list
const empty = query("SELECT t.Id FROM world.trainer t WHERE t.Type = 2 AND NOT EXISTS (SELECT 1 FROM world.trainer_spell s WHERE s.TrainerId = t.Id)").map((r) => Number(r[0]));
const masterSpells = new Map<number, number[]>();
for (const [t, s] of query(`SELECT TrainerId, SpellId FROM ref_master.trainer_spell WHERE TrainerId IN (${empty.join(",") || 0})`))
  (masterSpells.get(Number(t)) ?? masterSpells.set(Number(t), []).get(Number(t))!).push(Number(s));

// master's modern single-spell trainers have no SkillLineAbility in 5.5.4; their greeting names the profession
const GREETING: [RegExp, number][] = [
  [/alchemy/i, 171], [/herbs/i, 182], [/dug deep into the earth/i, 186], [/remove the leather/i, 393], [/beast hides/i, 165],
  [/precious gems/i, 755], [/ore that you find into weapons/i, 164], [/enchanting/i, 333], [/inscription/i, 773],
  [/engineering/i, 202], [/found cloth/i, 197], [/bind those wounds/i, 129], [/cook/i, 185], [/fish/i, 356], [/archaeolog/i, 794],
];
const greeting = new Map(query("SELECT Id, Greeting FROM world.trainer WHERE Type = 2").map(([id, g]) => [Number(id), g ?? ""] as [number, string]));
const FALLBACK = (trainer: number) => GREETING.find(([re]) => re.test(greeting.get(trainer) ?? ""))?.[1];

const lines = [
  "-- MoP Classic: profession trainer spells from SkyFire 5.4.8 npc_trainer lists, for tradeskill trainers that had none.",
  "-- Generated by tools/mop-content/gen_profession_trainers.ts; do not edit by hand.",
  "",
];
const inserts: string[] = [];
const done: string[] = [];
const unresolved: number[] = [];
for (const trainer of empty) {
  const skills = new Set((masterSpells.get(trainer) ?? []).map((s) => skillOfSpell.get(s)).filter((s): s is number => s !== undefined && s in LIST));
  if (skills.size === 0 && FALLBACK(trainer)) skills.add(FALLBACK(trainer)!);
  if (skills.size !== 1) { unresolved.push(trainer); continue; }
  const skill = [...skills][0];
  const seen = new Set<number>();
  for (const [, spell, cost, reqSkill, reqValue, reqLevel] of resolve(LIST[skill])) {
    const id = Number(spell);
    if (!clientSpells.has(id) || seen.has(id)) continue;
    seen.add(id);
    inserts.push(`(${trainer}, ${id}, ${cost}, ${reqSkill}, ${reqValue}, 0, 0, 0, ${reqLevel}, 0)`);
  }
  done.push(`${trainer}:${skill}`);
}
if (inserts.length) {
  lines.push(`DELETE FROM \`trainer_spell\` WHERE \`TrainerId\` IN (${done.map((d) => d.split(":")[0]).join(", ")});`);
  lines.push("INSERT INTO `trainer_spell` (`TrainerId`, `SpellId`, `MoneyCost`, `ReqSkillLine`, `ReqSkillRank`, `ReqAbility1`, `ReqAbility2`, `ReqAbility3`, `ReqLevel`, `VerifiedBuild`) VALUES");
  lines.push(inserts.join(",\n") + ";");
}

// Whittler Dewei (57620): menu 15125 trains herbalism/mining, its sub-menus 12185/12186 every profession (options 0-10)
const byProfession: Record<string, number> = {};
for (const d of done) { const [t, s] = d.split(":").map(Number); byProfession[s] ??= t; }
const OPTION_SKILL = [171, 164, 333, 202, 182, 773, 755, 165, 186, 393, 197];
const dewei: string[] = [];
const add = (menu: number, option: number, skill: number) => { if (byProfession[skill]) dewei.push(`(57620, ${byProfession[skill]}, ${menu}, ${option})`); };
add(15125, 4, 182);
add(15125, 8, 186);
for (const menu of [12185, 12186]) OPTION_SKILL.forEach((skill, option) => add(menu, option, skill));
lines.push("", "DELETE FROM `creature_trainer` WHERE `CreatureID` = 57620;");
lines.push("INSERT INTO `creature_trainer` (`CreatureID`, `TrainerID`, `MenuID`, `OptionID`) VALUES");
lines.push(dewei.join(",\n") + ";", "");
writeFileSync(out, lines.join("\n"));
console.log(out, done.length, "trainers", inserts.length, "spells", dewei.length, "Dewei links;", done.join(" "), "| unresolved:", unresolved.join(" "));
