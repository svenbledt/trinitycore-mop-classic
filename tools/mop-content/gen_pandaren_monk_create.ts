// Generates the world-DB update that makes Pandaren (24/25/26) and Monk (10) creatable (phase3-4-plan.md step 2).
// usage: bun tools/mop-content/gen_pandaren_monk_create.ts <db2 dir> [out.sql] [mysql container]
import { writeFileSync } from "node:fs";
import { readDb2 } from "./src/db2.ts";

const [db2Dir, outFile = "sql/updates/world/mop_classic/2026_10_18_00_world.sql", container = "tc-mop-db-1"] = process.argv.slice(2);
if (!db2Dir) throw new Error("usage: gen_pandaren_monk_create.ts <db2 dir> [out.sql] [container]");
const DBD = new URL("../mop-re/refs/wowdbdefs/definitions/", import.meta.url).pathname.replace(/^\/(\w:)/, "$1");
const db2 = (name: string) => readDb2(`${db2Dir}/${name}.db2`, `${DBD}${name}.dbd`).rows;

function q(sql: string): string[][] {
  const r = Bun.spawnSync(["docker", "exec", container, "mysql", "-uroot", "-proot", "-N", "-B", "-e", sql]);
  if (r.exitCode !== 0) throw new Error(`${sql}\n${r.stderr.toString()}`);
  return r.stdout.toString().split("\n").filter(Boolean).map(l => l.split("\t"));
}
const num = (v: string) => (v === "NULL" ? "NULL" : String(Number(v)));

const PANDAREN = [24, 25, 26], MONK = 10;
const inScope = (race: number, cls: number) => PANDAREN.includes(race) || cls === MONK;
const raceBit = (race: number) => 1n << BigInt(race - 1);
const classBit = (cls: number) => 1 << (cls - 1);

// Client data: CharBaseInfo is the list of race/class pairs the 5.5.4 client offers (matches the retail AUTH_RESPONSE class list).
const combos = db2("CharBaseInfo").map(r => [r.RaceID as number, r.ClassID as number] as const)
  .filter(([r, c]) => inScope(r, c)).sort((a, b) => a[0] - b[0] || a[1] - b[1]);
const comboSet = new Set(combos.map(([r, c]) => `${r}:${c}`));
const spells = new Set(db2("SpellName").map(r => r.ID as number));
const out: string[] = [];
const log = (s: string) => console.error(s);

out.push("-- MoP Classic: Pandaren (races 24/25/26) and Monk (class 10) character creation.");
out.push("-- Generated by tools/mop-content/gen_pandaren_monk_create.ts; do not edit by hand. Race/class pairs: client CharBaseInfo.db2.");
out.push("-- Sources: ref_master = TrinityCore master TDB, ref_sfdb = SkyFire 5.4.8 world DB (+ core updates), world = cata_classic TDB.");
out.push("");

// world_safe_locs 3295: Player::_LoadHomeBind falls back to it for neutral Pandaren (as in TC master).
{
  const r = q("SELECT ID, MapID, LocX, LocY, LocZ, Facing, TransportSpawnId, Comment FROM ref_master.world_safe_locs WHERE ID=3295")[0];
  out.push("-- world_safe_locs: ref_master.world_safe_locs ID 3295");
  out.push("DELETE FROM `world_safe_locs` WHERE `ID`=3295;");
  out.push("INSERT INTO `world_safe_locs` (`ID`,`MapID`,`LocX`,`LocY`,`LocZ`,`Facing`,`TransportSpawnId`,`Comment`) VALUES");
  out.push(`(${r.slice(0, 7).map(num).join(",")},'${r[7].replace(/'/g, "''")}');`, "");
}

// race_unlock_requirement: ref_master rows for the Pandaren races (expansion 4 = MoP).
{
  const rows = q(`SELECT raceID, expansion, achievementId FROM ref_master.race_unlock_requirement WHERE raceID IN (${PANDAREN})`);
  if (rows.length !== 3) throw new Error("race_unlock_requirement: expected 3 master rows");
  out.push("-- race_unlock_requirement: ref_master.race_unlock_requirement raceID 24-26");
  out.push(`DELETE FROM \`race_unlock_requirement\` WHERE \`raceID\` IN (${PANDAREN.join(",")});`);
  out.push("INSERT INTO `race_unlock_requirement` (`raceID`,`expansion`,`achievementId`) VALUES");
  out.push(rows.map(r => `(${r.join(",")})`).join(",\n") + ";", "");
}

// class_expansion_requirement: ref_master rows, limited to the CharBaseInfo pairs.
{
  const master = new Map(q("SELECT ClassID, RaceID, ActiveExpansionLevel, AccountExpansionLevel FROM ref_master.class_expansion_requirement")
    .map(r => [`${r[1]}:${r[0]}`, r]));
  const rows = combos.map(([r, c]) => {
    const m = master.get(`${r}:${c}`);
    if (!m) throw new Error(`class_expansion_requirement: no master row for race ${r} class ${c}`);
    return `(${m.join(",")})`;
  });
  out.push("-- class_expansion_requirement: ref_master.class_expansion_requirement for each CharBaseInfo pair (Monk needs expansion 4)");
  out.push(`DELETE FROM \`class_expansion_requirement\` WHERE \`ClassID\`=${MONK} OR \`RaceID\` IN (${PANDAREN.join(",")});`);
  out.push("INSERT INTO `class_expansion_requirement` (`ClassID`,`RaceID`,`ActiveExpansionLevel`,`AccountExpansionLevel`) VALUES");
  out.push(rows.join(",\n") + ";", "");
}

// Stats: SkyFire stores absolute per race/class stats; cata_classic splits them into class base + race modifier.
{
  const sf = new Map(q("SELECT race, class, level, str, agi, sta, inte, spi FROM ref_sfdb.player_levelstats")
    .map(r => [`${r[0]}:${r[1]}:${r[2]}`, r.slice(3).map(Number)]));
  const human = q("SELECT str, agi, sta, inte, spi FROM world.player_racestats WHERE race=1")[0].map(Number);
  if (human.some(v => v !== 0)) throw new Error("expected zero Human race modifiers in world.player_racestats");
  // Only SkyFire's MoP levels 86-90 carry race modifiers (they match world.player_racestats for most other races).
  const worldMods = new Map(q("SELECT race, str, agi, sta, inte, spi FROM world.player_racestats").map(r => [Number(r[0]), r.slice(1).join(",")]));
  const diffs = new Map<number, Map<string, number>>();
  for (const [k, v] of sf) {
    const [race, cls, lvl] = k.split(":").map(Number);
    const h = sf.get(`1:${cls}:${lvl}`);
    if (!h || lvl < 86) continue;
    const d = v.map((x, i) => x - h[i]).join(",");
    const m = diffs.get(race) ?? diffs.set(race, new Map()).get(race)!;
    m.set(d, (m.get(d) ?? 0) + 1);
  }
  for (const [race, m] of diffs) {
    if (race === 24 || !worldMods.has(race)) continue;
    if (m.size !== 1 || !m.has(worldMods.get(race)!)) log(`note: SkyFire 86-90 race ${race} modifier ${[...m.keys()]} != world ${worldMods.get(race)}`);
  }
  const panda = diffs.get(24)!;
  if (panda.size !== 1) throw new Error(`SkyFire Pandaren modifiers disagree: ${[...panda.keys()]}`);
  const [[mod, n]] = [...panda];
  log(`player_racestats: Pandaren - Human (SkyFire, levels 86-90): ${mod} in ${n} rows`);
  out.push(`-- player_racestats: ref_sfdb.player_levelstats race 24 minus race 1 at levels 86-90 (${n} rows agree)`);
  out.push(`DELETE FROM \`player_racestats\` WHERE \`race\` IN (${PANDAREN.join(",")});`);
  out.push("INSERT INTO `player_racestats` (`race`,`str`,`agi`,`sta`,`inte`,`spi`) VALUES");
  out.push(PANDAREN.map(r => `(${r},${mod})`).join(",\n") + ";", "");

  const monk: string[] = [];
  for (let lvl = 1; lvl <= 90; lvl++) {
    const v = sf.get(`1:${MONK}:${lvl}`);
    if (!v) throw new Error(`no SkyFire Human Monk stats for level ${lvl}`);
    monk.push(`(${MONK},${lvl},${v.join(",")},18414)`);
  }
  out.push("-- player_classlevelstats: Monk = ref_sfdb.player_levelstats race 1 class 10 (Human modifiers are 0), levels 1-90");
  out.push("-- TODO(verify): SkyFire's Monk curve copies Warrior up to 80; check against MoP base stats before levelling past 10.");
  out.push(`DELETE FROM \`player_classlevelstats\` WHERE \`class\`=${MONK};`);
  out.push("INSERT INTO `player_classlevelstats` (`class`,`level`,`str`,`agi`,`sta`,`inte`,`spi`,`VerifiedBuild`) VALUES");
  out.push(monk.join(",\n") + ";", "");
}

// playercreateinfo: one row per CharBaseInfo pair; the start position is the race's (world first, else Warrior row).
{
  const cols = "race, class, map, position_x, position_y, position_z, orientation, npe_map, npe_position_x, npe_position_y, npe_position_z, npe_orientation, npe_transport_guid, intro_movie_id, intro_scene_id, npe_intro_scene_id";
  const world = new Map(q(`SELECT ${cols} FROM world.playercreateinfo`).map(r => [`${r[0]}:${r[1]}`, r]));
  const master = new Map(q(`SELECT ${cols} FROM ref_master.playercreateinfo`).map(r => [`${r[0]}:${r[1]}`, r]));
  const extra = [...world.keys()].filter(k => { const [r, c] = k.split(":").map(Number); return inScope(r, c) && !comboSet.has(k); });
  if (extra.length) log(`playercreateinfo: dropping pairs the client does not offer: ${extra.join(" ")}`);
  out.push(`-- playercreateinfo: CharBaseInfo pairs only (drops ${extra.join(", ") || "none"}); new pairs copy the race's world Warrior position`);
  out.push(`DELETE FROM \`playercreateinfo\` WHERE \`class\`=${MONK} OR \`race\` IN (${PANDAREN.join(",")});`);
  out.push(`INSERT INTO \`playercreateinfo\` (\`${cols.split(", ").join("`,`")}\`) VALUES`);
  const rows = combos.map(([r, c]) => {
    let src = world.get(`${r}:${c}`), note = `world ${r}/${c}`;
    if (!src) { src = [...(world.get(`${r}:1`) ?? [])]; note = `world ${r}/1 position`; }
    if (!src.length) throw new Error(`playercreateinfo: no world row for race ${r}`);
    const row = [String(r), String(c), ...src.slice(2)];
    const m = master.get(`${r}:${c}`);
    const same = m && m.slice(2, 7).every((v, i) => Math.abs(Number(v) - Number(row[2 + i])) < 0.01);
    return `(${row.map(num).join(",")}) -- ${note}${m ? (same ? ", = ref_master" : ", ref_master differs") : ""}`;
  });
  out.push(rows.map((r, i) => (i < rows.length - 1 ? r.replace(") --", "), --") : r.replace(") --", "); --"))).join("\n"), "");
}

// playercreateinfo_action: SkyFire 5.4.8 bars (MoP spell IDs); 25/26 reuse the race 24 bar of the same class.
{
  const sf = q("SELECT race, class, button, action, type FROM ref_sfdb.playercreateinfo_action ORDER BY race, class, button");
  const by = new Map<string, string[][]>();
  for (const r of sf) by.set(`${r[0]}:${r[1]}`, [...(by.get(`${r[0]}:${r[1]}`) ?? []), r]);
  const rows: string[] = [];
  for (const [r, c] of combos) {
    const srcRace = by.has(`${r}:${c}`) ? r : 24;
    const bar = by.get(`${srcRace}:${c}`);
    if (!bar) { log(`playercreateinfo_action: no SkyFire bar for ${r}/${c}`); continue; }
    for (const [, , button, action, type] of bar) {
      if (type === "0" && !spells.has(Number(action))) { log(`playercreateinfo_action: ${r}/${c} spell ${action} not in SpellName.db2, skipped`); continue; }
      rows.push(`(${r},${c},${button},${action},${type}) -- ref_sfdb ${srcRace}/${c}`);
    }
  }
  out.push("-- playercreateinfo_action: ref_sfdb.playercreateinfo_action (spells checked against SpellName.db2)");
  out.push(`DELETE FROM \`playercreateinfo_action\` WHERE \`class\`=${MONK} OR \`race\` IN (${PANDAREN.join(",")});`);
  out.push("INSERT INTO `playercreateinfo_action` (`race`,`class`,`button`,`action`,`type`) VALUES");
  out.push(rows.map((r, i) => r.replace(") --", i < rows.length - 1 ? "), --" : "); --")).join("\n"), "");
}

// playercreateinfo_cast_spell: Pandaren rows from master, Monk additions to the race rows cata_classic has without Monk.
{
  type Cast = { race: bigint; cls: number; spell: number; note: string; src: string };
  const casts: Cast[] = [];
  const pandarenClasses = combos.filter(([r]) => r === 24).map(([, c]) => c);
  for (const r of q("SELECT raceMask, classMask, spell, note FROM ref_master.playercreateinfo_cast_spell WHERE raceMask=8388608")) {
    const cls = Number(r[1]) && pandarenClasses.reduce((m, c) => m | (Number(r[1]) & classBit(c)), 0);
    if (Number(r[1]) && !cls) continue;
    casts.push({ race: raceBit(24), cls, spell: Number(r[2]), note: r[3].replace(" and Warlock", ""), src: "ref_master" });
  }
  const sfPet = q("SELECT racemask, classmask, Spell, Note FROM ref_sfdb.playercreateinfo_spell_cast WHERE racemask=8388608 AND classmask=4 AND Note LIKE '%Turtle%'")[0];
  casts.push({ race: raceBit(24), cls: classBit(3), spell: Number(sfPet[2]), note: sfPet[3], src: "ref_sfdb (cata_classic gives each race's hunter a pet)" });
  casts.push({ race: raceBit(7), cls: classBit(MONK), spell: 80653, note: "Monk - Gnome - Irradiated Aura", src: "ref_master" });
  casts.push({ race: raceBit(8), cls: classBit(MONK), spell: 71033, note: "Troll - Monk - Calm of the Novice", src: "ref_sfdb (racemask 128, all classes)" });
  const rows: string[] = [];
  for (const c of casts) {
    if (!spells.has(c.spell)) { log(`playercreateinfo_cast_spell: spell ${c.spell} not in SpellName.db2, skipped`); continue; }
    rows.push(`(${c.race},${c.cls},0,${c.spell},'${c.note.replace(/'/g, "''")}') -- ${c.src}`);
  }
  out.push("-- playercreateinfo_cast_spell: Pandaren rows from ref_master (Mage/Warlock row limited to Mage), hunter pet from ref_sfdb,");
  out.push("-- Gnome/Troll Monk rows for the race auras cata_classic only casts on pre-Monk class masks. Spells checked against SpellName.db2.");
  out.push(`DELETE FROM \`playercreateinfo_cast_spell\` WHERE \`raceMask\`=${raceBit(24)} OR (\`classMask\`=${classBit(MONK)} AND \`spell\` IN (80653,71033));`);
  out.push("INSERT INTO `playercreateinfo_cast_spell` (`raceMask`,`classMask`,`createMode`,`spell`,`note`) VALUES");
  out.push(rows.map((r, i) => r.replace(") --", i < rows.length - 1 ? "), --" : "); --")).join("\n"), "");
}

writeFileSync(outFile, out.join("\n").replace(/\n+$/, "\n"));
log(`wrote ${outFile} (${combos.length} race/class pairs)`);
