// Generates a world update setting creature DamageModifier from retail 5.5.4 sniffs: for every attacker entry with enough normal
// (non-crit) melee hits, scale the current modifier by retail median hit / our predicted mean hit
// ((basedamage x [1, 1.5] + AP/14) x DamageModifier x attack time). Hits on creatures are preferred over hits on players (armor).
// usage: bun tools/mop-content/gen_creature_sniff_damage.ts <out.sql> <sniff.pkt>... [--container name]
import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";

const args = process.argv.slice(2);
const ci = args.indexOf("--container");
const container = ci >= 0 ? args.splice(ci, 2)[1] : "tc-mop-db-1";
const [out, ...pkts] = args;
const MIN_HITS = 5;

function query(sql: string): string[][] {
  const res = execFileSync("docker", ["exec", container, "mysql", "-uroot", "-proot", "-N", "-B", "-e", sql], { encoding: "utf8", stdio: ["ignore", "pipe", "ignore"], maxBuffer: 1 << 28 });
  return res.split("\n").filter((l) => l.length).map((l) => l.split("\t"));
}

const creature = new Map<number, { level: number; mod: number; cls: number; attackTime: number }>();
for (const [e, lv, mod, cls, at] of query("SELECT d.Entry, d.MinLevel, d.DamageModifier, t.unit_class, t.BaseAttackTime FROM world.creature_template_difficulty d JOIN world.creature_template t ON t.entry = d.Entry WHERE d.DifficultyID = 0"))
  creature.set(Number(e), { level: Number(lv), mod: Number(mod), cls: Number(cls), attackTime: Number(at) });
const stats = new Map<string, { dmg: number; ap: number }>();
for (const [lv, cls, dmg, ap] of query("SELECT m.level, m.class, m.basedamage, c.attackpower FROM world.creature_classlevelstats_mop m JOIN world.creature_classlevelstats c ON c.level = m.level AND c.class = m.class"))
  stats.set(`${lv}:${cls}`, { dmg: Number(dmg), ap: Number(ap) });

function readGuid(b: Buffer, p: number): [bigint, number] {
  const lo = b[p], hi = b[p + 1];
  p += 2;
  for (let i = 0; i < 8; ++i) if ((lo >> i) & 1) ++p;
  let high = 0n;
  for (let i = 0; i < 8; ++i) if ((hi >> i) & 1) high |= BigInt(b[p++]) << BigInt(8 * i);
  return [high, p];
}

// attacker entry -> [hits on creatures, hits on players]
const hits = new Map<number, [number[], number[]]>();
for (const file of pkts) {
  const b = readFileSync(file);
  let o = 62;
  o += 4 + b.readUInt32LE(o);
  while (o + 20 <= b.length) {
    const opt = b.readUInt32LE(o + 12), len = b.readUInt32LE(o + 16);
    o += 20 + opt;
    const op = b.readUInt32LE(o);
    const d = b.subarray(o + 4, o + len);
    o += len;
    if (op !== 0x4c0030 || d.length < 40) continue; // SMSG_ATTACKER_STATE_UPDATE
    const hitInfo = d.readUInt32LE(5);
    const [attacker, p1] = readGuid(d, 9);
    const [victim, p2] = readGuid(d, p1);
    const damage = d.readInt32LE(p2);
    if ((attacker >> 58n) !== 8n || (hitInfo & 0x200) || damage <= 0) continue; // creature attacker, no crits
    const entry = Number((attacker >> 6n) & 0x7fffffn);
    const h = hits.get(entry) ?? [[], []];
    h[(victim >> 58n) === 2n ? 1 : 0].push(damage);
    hits.set(entry, h);
  }
}

const median = (a: number[]) => { const s = [...a].sort((x, y) => x - y); return s[Math.floor(s.length / 2)]; };
const lines = [
  "-- MoP Classic: creature DamageModifier derived from retail 5.5.4.70449 melee hits (median non-crit hit vs our formula).",
  "-- Generated by tools/mop-content/gen_creature_sniff_damage.ts; do not edit by hand.",
  "",
];
let count = 0;
for (const [entry, [onCreatures, onPlayers]] of [...hits].sort((a, b) => a[0] - b[0])) {
  const c = creature.get(entry);
  const sample = onCreatures.length >= MIN_HITS ? onCreatures : onPlayers.length >= MIN_HITS ? onPlayers : null;
  if (!c || !sample || !c.mod) continue;
  const s = stats.get(`${c.level}:${c.cls}`);
  if (!s) continue;
  const mean = ((s.dmg * 1.25 + s.ap / 14) * c.mod * c.attackTime) / 1000;
  if (mean <= 0) continue;
  const mod = Number((c.mod * (median(sample) / mean)).toPrecision(3));
  lines.push(`UPDATE \`creature_template_difficulty\` SET \`DamageModifier\` = ${mod} WHERE \`Entry\` = ${entry} AND \`DifficultyID\` = 0; -- retail median ${median(sample)} over ${sample.length} hits`);
  ++count;
}
lines.push("");
writeFileSync(out, lines.join("\n"));
console.log(out, count, "creatures");
