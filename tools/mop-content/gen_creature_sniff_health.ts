// Generates a world update that sets level and health modifier of every creature seen in retail 5.5.4 sniffs (1:1 retail).
// Input: WPP 554 parses of the sniffs (EntryID / MaxHealth / Level of each create); health uses the MoP curve
// (creature_classlevelstats_mop), so HealthModifier = retail MaxHealth / MoP base health at that level and class.
// usage: bun tools/mop-content/gen_creature_sniff_health.ts <out.sql> <parsed.txt>... [--container name]
import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";

const args = process.argv.slice(2);
const ci = args.indexOf("--container");
const container = ci >= 0 ? args.splice(ci, 2)[1] : "tc-mop-db-1";
const [out, ...parsed] = args;

function query(sql: string): string[][] {
  const res = execFileSync("docker", ["exec", container, "mysql", "-uroot", "-proot", "-N", "-B", "-e", sql], { encoding: "utf8", stdio: ["ignore", "pipe", "ignore"], maxBuffer: 1 << 28 });
  return res.split("\n").filter((l) => l.length).map((l) => l.split("\t"));
}

const base = new Map<string, number>();
for (const [lv, cl, hp] of query("SELECT level, class, basehp FROM world.creature_classlevelstats_mop")) base.set(`${lv}:${cl}`, Number(hp));
const unitClass = new Map<number, number>();
for (const [e, c] of query("SELECT entry, unit_class FROM world.creature_template")) unitClass.set(Number(e), Number(c));

// entry -> "level:maxHealth" -> count
const seen = new Map<number, Map<string, number>>();
const re = /^\[\d+\] (EntryID|MaxHealth|Level): (-?\d+)/;
for (const file of parsed) {
  let entry = 0, maxHealth = -1;
  for (const line of readFileSync(file, "utf8").split("\n")) {
    const m = re.exec(line);
    if (!m) continue;
    const v = Number(m[2]);
    if (m[1] === "EntryID") { entry = v; maxHealth = -1; continue; }
    if (m[1] === "MaxHealth") { maxHealth = v; continue; }
    if (entry && maxHealth > 0) {
      const key = `${v}:${maxHealth}`;
      const s = seen.get(entry) ?? new Map<string, number>();
      s.set(key, (s.get(key) ?? 0) + 1);
      seen.set(entry, s);
      entry = 0;
    }
  }
}

const lines = [
  "-- MoP Classic: creature level and health modifier as seen in retail 5.5.4.70449 sniffs (most common level/MaxHealth per entry).",
  "-- Generated by tools/mop-content/gen_creature_sniff_health.ts; do not edit by hand. Health uses expansion 4 (creature_classlevelstats_mop).",
  "",
];
let count = 0;
for (const [entry, obs] of [...seen].sort((a, b) => a[0] - b[0])) {
  const cls = unitClass.get(entry);
  if (!cls) continue;
  const levels = [...obs.keys()].map((k) => Number(k.split(":")[0]));
  const [best] = [...obs].sort((a, b) => b[1] - a[1]);
  const [lv, mh] = best[0].split(":").map(Number);
  const b = base.get(`${lv}:${cls}`);
  if (!b) continue;
  const mod = Math.round((mh / b) * 10000) / 10000;
  lines.push(`UPDATE \`creature_template_difficulty\` SET \`MinLevel\` = ${Math.min(...levels)}, \`MaxLevel\` = ${Math.max(...levels)}, \`HealthScalingExpansion\` = 4, \`HealthModifier\` = ${mod} WHERE \`Entry\` = ${entry} AND \`DifficultyID\` = 0; -- retail ${mh} HP at ${lv}`);
  ++count;
}
lines.push("");
writeFileSync(out, lines.join("\n"));
console.log(out, count, "creatures");
